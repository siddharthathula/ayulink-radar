#!/usr/bin/env python3
"""Export the trained rhythm model to JSON, C headers and a C parity test.

Inputs:  ml/out/metrics.json (written by train_rhythm.py), ml/data/afdb/*
Outputs:
    web/public/model/rhythm_model.json
    web/public/model/parity.json
    web/public/model/samples.json
    firmware/rhythm_model.h
    firmware/rhythm_infer.h
    firmware/rhythm_samples.h
    firmware/rhythm_parity_test.c

Run:
    python ml/export_model.py
"""
from __future__ import annotations

import json
import math
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
from sklearn.model_selection import GroupKFold

from features import FEATURES, extract_features
from train_rhythm import N_FOLDS, build_dataset

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent
OUT = ROOT / "out"
WEB_MODEL = REPO / "web" / "public" / "model"
FIRMWARE = REPO / "firmware"


def evenly_spaced(values: list[int], count: int) -> list[int]:
    if len(values) <= count:
        return values
    if count == 1:
        return [values[0]]
    step = (len(values) - 1) / (count - 1)
    return [values[int(round(i * step))] for i in range(count)]


def rr_quality_ok(rr: list[int]) -> bool:
    """Mirror of web/lib/engine/signalQuality.ts rrWindowQuality."""
    if len(rr) < 30:
        return False
    bad = sum(1 for value in rr if value < 300 or value > 2000)
    return bad / len(rr) <= 0.2


def prob_from_state(features: list[float], state: dict) -> float:
    total = state["intercept"]
    for value, mean, scale, coef in zip(
        features, state["mean"], state["scale"], state["coef"]
    ):
        total += coef * ((value - mean) / scale)
    return 1.0 / (1.0 + math.exp(-total))


def c_float(value: float) -> str:
    return f"{value:.9g}f"


def write_model_json(metrics: dict, state: dict) -> None:
    model = {
        "features": FEATURES,
        "mean": state["mean"],
        "scale": state["scale"],
        "coef": state["coef"],
        "intercept": state["intercept"],
        "threshold": metrics["threshold"],
        "windowBeats": 30,
        "metrics": {
            "dataSource": metrics["dataset"],
            "license": metrics["dataLicense"],
            "split": metrics["split"],
            "nWindows": metrics["nWindows"],
            "nAf": metrics["nAf"],
            "nNormal": metrics["nNormal"],
            "nRecords": metrics["nRecords"],
            "thresholdRule": metrics["thresholdRule"],
            "folds": metrics["folds"],
            "mean": metrics["mean"],
            "sd": metrics["sd"],
            "outOfFold": metrics["outOfFold"],
            "generatedAt": metrics["generatedAt"],
        },
        "trainedOn": (
            "MIT-BIH Atrial Fibrillation Database (afdb), 25 records, "
            "30-RR windows, GroupKFold(5) by record"
        ),
        "license": (
            "Model trained on ODC-BY 1.0 data. Cite Moody & Mark 1983 and "
            "PhysioNet. Intended for screening research, not diagnosis."
        ),
        "generatedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    (WEB_MODEL / "rhythm_model.json").write_text(json.dumps(model, indent=2) + "\n")


def write_model_header(state: dict, threshold: float) -> None:
    lines = [
        "/* Generated by ml/export_model.py. Do not edit by hand. */",
        "#ifndef AYULINK_RHYTHM_MODEL_H",
        "#define AYULINK_RHYTHM_MODEL_H",
        "",
        "#define AYU_FEATURE_COUNT 9",
        "#define AYU_WINDOW_BEATS 30",
        "",
        "static const float AYU_MEAN[AYU_FEATURE_COUNT] = {",
        "    " + ", ".join(c_float(v) for v in state["mean"]),
        "};",
        "",
        "static const float AYU_SCALE[AYU_FEATURE_COUNT] = {",
        "    " + ", ".join(c_float(v) for v in state["scale"]),
        "};",
        "",
        "static const float AYU_COEF[AYU_FEATURE_COUNT] = {",
        "    " + ", ".join(c_float(v) for v in state["coef"]),
        "};",
        "",
        f"static const float AYU_INTERCEPT = {c_float(state['intercept'])};",
        f"static const float AYU_THRESHOLD = {c_float(threshold)};",
        "",
        "#endif",
        "",
    ]
    header = "\n".join(lines)
    (FIRMWARE / "rhythm_model.h").write_text(header)
    demo = FIRMWARE / "rhythm_demo"
    demo.mkdir(exist_ok=True)
    (demo / "rhythm_model.h").write_text(header)


C_INFER = r"""/* Generated by ml/export_model.py. Do not edit by hand.
 *
 * Pure C implementation of the nine features in ml/features.py and
 * web/lib/engine/rhythm.ts. Host-tested against Python; not yet validated
 * on-device.
 */
#ifndef AYULINK_RHYTHM_INFER_H
#define AYULINK_RHYTHM_INFER_H

#include <math.h>
#include <stdint.h>

#include "rhythm_model.h"

static inline double ayu_sigmoid(double s) {
    if (s >= 0.0) {
        return 1.0 / (1.0 + exp(-s));
    }
    double e = exp(s);
    return e / (1.0 + e);
}

/* 30-RR window, each value in milliseconds. Returns -1 for a wrong length. */
static inline float ayu_rhythm_prob(const uint16_t *rr_ms, int n) {
    if (rr_ms == 0 || n != AYU_WINDOW_BEATS) {
        return -1.0f;
    }

    double x[AYU_WINDOW_BEATS];
    double sum = 0.0;
    for (int i = 0; i < n; i++) {
        x[i] = (double)rr_ms[i];
        sum += x[i];
    }
    double mean_rr = sum / n;

    double var_rr = 0.0;
    for (int i = 0; i < n; i++) {
        double d = x[i] - mean_rr;
        var_rr += d * d;
    }
    var_rr /= n;
    double sdnn = sqrt(var_rr);

    double diff[AYU_WINDOW_BEATS - 1];
    double diff_sum = 0.0;
    double sq_sum = 0.0;
    int pnn50 = 0;
    for (int i = 0; i < n - 1; i++) {
        diff[i] = x[i + 1] - x[i];
        diff_sum += diff[i];
        sq_sum += diff[i] * diff[i];
        if (fabs(diff[i]) > 50.0) {
            pnn50++;
        }
    }
    int ndiff = n - 1;
    double rmssd = sqrt(sq_sum / ndiff);
    double pnn50_frac = (double)pnn50 / (double)ndiff;
    double cv = sdnn / mean_rr;
    double nrmssd = rmssd / mean_rr;

    double mean_diff = diff_sum / ndiff;
    double var_diff = 0.0;
    for (int i = 0; i < ndiff; i++) {
        double d = diff[i] - mean_diff;
        var_diff += d * d;
    }
    var_diff /= ndiff;
    double sd1 = sqrt(0.5) * sqrt(var_diff);
    double inner = 2.0 * sdnn * sdnn - sd1 * sd1;
    double sd2 = sqrt(inner > 1e-9 ? inner : 1e-9);
    double sd_ratio = sd1 / sd2;

    int counts[16] = {0};
    for (int i = 0; i < ndiff; i++) {
        double z = diff[i] / mean_rr;
        if (z < -0.5) z = -0.5;
        if (z > 0.5) z = 0.5;
        int idx = (int)floor((z + 0.5) * 16.0);
        if (idx == 16) idx = 15;
        if (idx < 0) idx = 0;
        counts[idx]++;
    }
    double entropy = 0.0;
    for (int i = 0; i < 16; i++) {
        if (counts[i] > 0) {
            double p = (double)counts[i] / (double)ndiff;
            entropy -= p * log(p);
        }
    }

    int turning = 0;
    for (int i = 1; i < n - 1; i++) {
        if ((x[i] - x[i - 1]) * (x[i + 1] - x[i]) < 0.0) {
            turning++;
        }
    }
    double tpr = (double)turning / (double)(n - 2);

    double f[AYU_FEATURE_COUNT] = {
        mean_rr, sdnn, rmssd, pnn50_frac, cv, nrmssd, sd_ratio, entropy, tpr
    };
    double score = AYU_INTERCEPT;
    for (int i = 0; i < AYU_FEATURE_COUNT; i++) {
        score += (double)AYU_COEF[i] *
                 ((f[i] - (double)AYU_MEAN[i]) / (double)AYU_SCALE[i]);
    }
    return (float)ayu_sigmoid(score);
}

/* Equivalent of rrWindowQuality() for a 30+ interval window. */
static inline int ayu_rr_quality_ok(const uint16_t *rr_ms, int n) {
    if (rr_ms == 0 || n < 30) {
        return 0;
    }
    int bad = 0;
    for (int i = 0; i < n; i++) {
        if (rr_ms[i] < 300 || rr_ms[i] > 2000) {
            bad++;
        }
    }
    return bad * 5 <= n; /* at most 20% out of range */
}

#endif
"""
(FIRMWARE / "rhythm_infer.h").write_text(C_INFER)
(FIRMWARE / "rhythm_demo" / "rhythm_infer.h").write_text(C_INFER)


def write_samples_and_parity(
    rr_windows: np.ndarray,
    y: np.ndarray,
    groups: np.ndarray,
    state: dict,
) -> None:
    gkf = GroupKFold(n_splits=N_FOLDS)
    fold_of = np.zeros(len(y), dtype=int)
    fold_indices: dict[int, list[int]] = {}
    for fold_idx, (_, test_idx) in enumerate(gkf.split(rr_windows, y, groups), start=1):
        fold_of[test_idx] = fold_idx
        fold_indices[fold_idx] = test_idx.tolist()

    af_samples: list[int] = []
    normal_samples: list[int] = []
    parity_idx: list[int] = []

    for fold in range(1, N_FOLDS + 1):
        test_idx = fold_indices[fold]
        af = [
            i for i in test_idx if y[i] == 1 and rr_quality_ok(rr_windows[i].tolist())
        ]
        normal = [
            i for i in test_idx if y[i] == 0 and rr_quality_ok(rr_windows[i].tolist())
        ]
        picked_af = evenly_spaced(af, 4)
        picked_normal = evenly_spaced(normal, 4)
        if len(picked_af) < 4 or len(picked_normal) < 4:
            raise SystemExit(
                f"fold {fold}: not enough quality-passing samples "
                f"(AF {len(af)}, normal {len(normal)})"
            )
        af_samples.extend(picked_af)
        normal_samples.extend(picked_normal)
        parity_idx.extend(picked_af[:2])
        parity_idx.extend(picked_normal[:2])

    # Interleave AF and normal so chip order does not reveal the label.
    samples: list[dict] = []
    for i in range(20):
        samples.append(
            {
                "id": f"S{2 * i + 1:02d}",
                "label": 1,
                "rr": [int(v) for v in rr_windows[af_samples[i]]],
            }
        )
        samples.append(
            {
                "id": f"S{2 * i + 2:02d}",
                "label": 0,
                "rr": [int(v) for v in rr_windows[normal_samples[i]]],
            }
        )

    (WEB_MODEL / "samples.json").write_text(
        json.dumps(samples, indent=1) + "\n"
    )

    parity: list[dict] = []
    for idx in parity_idx:
        rr = [int(v) for v in rr_windows[idx]]
        prob = prob_from_state(extract_features(rr), state)
        parity.append({"rr": rr, "prob": prob})
    (WEB_MODEL / "parity.json").write_text(json.dumps(parity, indent=1) + "\n")

    # Four samples baked into the firmware replay demo (2 AF, 2 normal).
    header: list[str] = [
        "/* Generated by ml/export_model.py. Public ECG-derived RR samples. */",
        "#ifndef AYULINK_RHYTHM_SAMPLES_H",
        "#define AYULINK_RHYTHM_SAMPLES_H",
        "",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        "#define AYU_DEMO_SAMPLE_COUNT 4",
        "",
    ]
    chosen = [samples[0], samples[1], samples[2], samples[3]]
    for j, sample in enumerate(chosen):
        values = ", ".join(str(int(v)) for v in sample["rr"])
        header.append(f"static const uint16_t AYU_DEMO_RR_{j}[30] = {{ {values} }};")
        header.append(f"static const int AYU_DEMO_LABEL_{j} = {sample['label']};")
        header.append(f'static const char *AYU_DEMO_ID_{j} = "{sample["id"]}";')
        header.append("")
    header.append("static const uint16_t *AYU_DEMO_RR[AYU_DEMO_SAMPLE_COUNT] = {")
    header.append(", ".join(f"AYU_DEMO_RR_{j}" for j in range(4)))
    header.append("};")
    header.append("static const int AYU_DEMO_LABEL[AYU_DEMO_SAMPLE_COUNT] = {")
    header.append(", ".join(f"AYU_DEMO_LABEL_{j}" for j in range(4)))
    header.append("};")
    header.append("static const char *AYU_DEMO_ID[AYU_DEMO_SAMPLE_COUNT] = {")
    header.append(", ".join(f"AYU_DEMO_ID_{j}" for j in range(4)))
    header.append("};")
    header.append("")
    header.append("#endif")
    header.append("")
    sample_header = "\n".join(header)
    (FIRMWARE / "rhythm_samples.h").write_text(sample_header)
    (FIRMWARE / "rhythm_demo" / "rhythm_samples.h").write_text(sample_header)

    # Host parity test.
    lines: list[str] = [
        "/* Generated by ml/export_model.py. Host parity test for the C model. */",
        "#include <math.h>",
        "#include <stdio.h>",
        '#include "rhythm_infer.h"',
        "",
        f"#define N_ROWS {len(parity)}",
        "static const uint16_t ROWS[N_ROWS][30] = {",
    ]
    for row in parity:
        lines.append("    { " + ", ".join(str(v) for v in row["rr"]) + " },")
    lines.append("};")
    lines.append("static const float EXPECTED[N_ROWS] = {")
    lines.append("    " + ", ".join(f"{row['prob']:.12f}f" for row in parity))
    lines.append("};")
    lines.append(
        """
int main(void) {
    float worst = 0.0f;
    for (int i = 0; i < N_ROWS; i++) {
        float got = ayu_rhythm_prob(ROWS[i], 30);
        float diff = fabsf(got - EXPECTED[i]);
        if (diff > worst) worst = diff;
        printf("row %2d: C=%.9f Python=%.9f diff=%.3e\\n",
               i, got, EXPECTED[i], diff);
    }
    printf("worst absolute difference: %.3e (tolerance 1e-4)\\n", worst);
    return worst <= 1e-4f ? 0 : 1;
}
"""
    )
    (FIRMWARE / "rhythm_parity_test.c").write_text("\n".join(lines))


def main() -> int:
    WEB_MODEL.mkdir(parents=True, exist_ok=True)
    metrics_path = OUT / "metrics.json"
    if not metrics_path.exists():
        raise SystemExit("Run ml/train_rhythm.py first.")
    metrics = json.loads(metrics_path.read_text())
    state = metrics["finalModel"]

    rr_windows, y, groups, _ = build_dataset()

    write_model_json(metrics, state)
    write_model_header(state, metrics["threshold"])
    write_samples_and_parity(rr_windows, y, groups, state)
    print(f"Wrote {WEB_MODEL / 'rhythm_model.json'}")
    print(f"Wrote {WEB_MODEL / 'parity.json'} and samples.json")
    print("Wrote firmware/rhythm_model.h, rhythm_infer.h, rhythm_samples.h")
    print("Wrote firmware/rhythm_parity_test.c")
    return 0


if __name__ == "__main__":
    sys.exit(main())
